from database import query_db, execute_db

def get_all_alerts(status=None, alert_type=None, risk_level=None, limit=None):
    """
    Retrieves predictive infrastructure failure alerts joined with asset metadata.
    
    How it works:
    1. Joins `alerts` with `assets` on `al.asset_id = a.id` to include location,
       asset name, and health index.
    2. Supports filtering by:
       - `status` ('Pending', 'In Progress', 'Resolved').
       - `alert_type` ('Critical', 'Warning', 'Maintenance').
       - `risk_level` ('High Risk', 'Medium Risk', 'Low Risk').
    3. Orders Critical alerts first, followed by Warning and Maintenance, sorted by creation time descending.
    4. Limits records if `limit` parameter is provided.
    
    Args:
        status (str, optional): Filter by alert resolution state.
        alert_type (str, optional): Filter by category severity.
        risk_level (str, optional): Filter by AI risk tier.
        limit (int, optional): Maximum records to return.
        
    Returns:
        list[dict]: List of enriched alert dictionaries.
    """
    query = """
        SELECT al.id, al.asset_id, al.alert_type, al.problem, al.risk_level,
               al.recommended_action, al.status, al.created_at,
               a.asset_tag, a.name AS asset_name, a.asset_type, a.location, a.health_score
        FROM alerts al
        JOIN assets a ON al.asset_id = a.id
        WHERE 1=1
    """
    params = []
    
    if status and status.lower() != 'all':
        query += " AND al.status = %s"
        params.append(status)
        
    if alert_type and alert_type.lower() != 'all':
        query += " AND al.alert_type = %s"
        params.append(alert_type)
        
    if risk_level and risk_level.lower() != 'all':
        query += " AND al.risk_level = %s"
        params.append(risk_level)
        
    query += " ORDER BY CASE al.alert_type WHEN 'Critical' THEN 1 WHEN 'Warning' THEN 2 ELSE 3 END, al.created_at DESC"
    
    if limit:
        query += f" LIMIT {int(limit)}"
        
    query += ";"
    return query_db(query, tuple(params))

def get_alert_by_id(alert_id):
    """
    Retrieves a single predictive alert by ID with associated asset details.
    
    How it works:
    - Joins `alerts` and `assets` filtering on `al.id = %s`.
    - Used when converting an alert into an active maintenance work order.
    
    Args:
        alert_id (int): Primary key ID of the alert.
        
    Returns:
        dict | None: The alert dictionary or None if not found.
    """
    query = """
        SELECT al.id, al.asset_id, al.alert_type, al.problem, al.risk_level,
               al.recommended_action, al.status, al.created_at,
               a.asset_tag, a.name AS asset_name, a.asset_type, a.location, a.health_score
        FROM alerts al
        JOIN assets a ON al.asset_id = a.id
        WHERE al.id = %s;
    """
    return query_db(query, (alert_id,), one=True)

def create_alert(asset_id, alert_type, problem, risk_level, recommended_action):
    """
    Creates a new predictive alert generated by AI anomaly detection or staff inspection.
    
    How it works:
    - Inserts a new record into `alerts` defaulting status to 'Pending'.
    - Stores the diagnostic problem description and AI recommended maintenance action.
    
    Args:
        asset_id (int): ID of the affected asset.
        alert_type (str): Severity category ('Critical', 'Warning', 'Maintenance').
        problem (str): Diagnostic problem description.
        risk_level (str): Classification ('High Risk', 'Medium Risk', 'Low Risk').
        recommended_action (str): Prescribed maintenance task.
        
    Returns:
        int: Primary key ID of the newly created alert.
    """
    return execute_db(
        """INSERT INTO alerts (asset_id, alert_type, problem, risk_level, recommended_action, status)
           VALUES (%s, %s, %s, %s, %s, 'Pending');""",
        (int(asset_id), alert_type, problem, risk_level, recommended_action),
        return_id=True
    )

def update_alert_status(alert_id, new_status):
    """
    Updates the operational lifecycle state of an alert.
    
    How it works:
    - Modifies `status` to 'Pending', 'In Progress', or 'Resolved'.
    
    Args:
        alert_id (int): ID of the alert.
        new_status (str): Target status value.
        
    Returns:
        int: Number of rows affected.
    """
    return execute_db("UPDATE alerts SET status = %s WHERE id = %s;", (new_status, alert_id))

def get_alert_counts():
    """
    Computes count of active unresolved alerts for top navigation and dashboard badges.
    
    How it works:
    - Filters alerts with status in ('Pending', 'In Progress').
    - Groups by `alert_type` to calculate individual counts for Critical, Warning, and Maintenance.
    - Computes total unresolved count.
    
    Returns:
        dict: Alert counts: {'Critical': X, 'Warning': Y, 'Maintenance': Z, 'total': N}.
    """
    rows = query_db("""
        SELECT alert_type, COUNT(*) AS cnt
        FROM alerts
        WHERE status IN ('Pending', 'In Progress')
        GROUP BY alert_type;
    """)
    res = {'Critical': 0, 'Warning': 0, 'Maintenance': 0, 'total': 0}
    for r in rows:
        if r['alert_type'] in res:
            res[r['alert_type']] = r['cnt']
            res['total'] += r['cnt']
    return res
